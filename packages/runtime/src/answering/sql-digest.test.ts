import { describe, expect, it } from "vitest";
import { readFileSync, readdirSync } from "node:fs";
import { aggregatingBlocks, aggregationCapacity, degeneratedOuterJoins, digestSql, type QueryDigest } from "./sql-digest.js";
import { evaluateSpecRealization } from "./realization-check.js";
import { parseFieldValue } from "./fields.js";
import type { SpecFields } from "./model.js";

const parsed = (sql: string, dialect?: Parameters<typeof digestSql>[1]): QueryDigest => {
  const digest = digestSql(sql, dialect);
  if (digest.status !== "parsed") throw new Error(`expected a digest: ${digest.reason}`);
  return digest;
};
const specified = (path: string, value: unknown) => ({ state: "specified", value: parseFieldValue(path as never, value), basis: { kind: "assumed" } });
const fieldsOf = (values: Record<string, unknown>) => Object.fromEntries(Object.entries(values).map(([path, value]) => [path, specified(path, value)])) as unknown as SpecFields;

const CTE_WINDOW = `
  WITH per_player AS (
    SELECT c.country, p.id AS player_id, SUM(m.runs) AS runs
    FROM players p JOIN matches m ON m.player_id = p.id LEFT JOIN countries c ON c.id = p.country_id
    WHERE m.season >= 2010
    GROUP BY c.country, p.id
  )
  SELECT country, AVG(runs) AS avg_runs, RANK() OVER (ORDER BY AVG(runs) DESC) AS rk
  FROM per_player GROUP BY country HAVING COUNT(*) > 3 ORDER BY avg_runs DESC LIMIT 10`;

describe("T5.1 Query Digest", () => {
  for (const dialect of ["sqlite", "mysql", "postgres"] as const) {
    it(`reads a CTE with joins, a window and HAVING (${dialect})`, () => {
      const digest = parsed(CTE_WINDOW, dialect);
      expect(digest.tables.sort()).toEqual(["countries", "matches", "players"]);
      const [outer, cte] = digest.blocks;
      expect(outer).toMatchObject({ kind: "outer", depth: 0, limit: 10, orderBy: true, groupBy: [{ column: "country" }], windows: 1 });
      expect(outer!.filters.map((filter) => filter.stage)).toEqual(["having"]);
      expect(cte).toMatchObject({ kind: "cte", name: "per_player", depth: 1, groupBy: [{ table: "c", column: "country" }, { table: "p", column: "id" }] });
      expect(cte!.relations.map((relation) => [relation.table, relation.join ?? "from"])).toEqual([["players", "from"], ["matches", "inner"], ["countries", "left"]]);
      expect(cte!.filters.map((filter) => filter.stage)).toEqual(["on", "on", "where"]);
      expect(outer!.reads).toEqual([cte!.id]);
      expect(aggregationCapacity(digest)).toBe(2);
    });

    it(`reads a FROM subquery, a scalar subquery and DISTINCT counts (${dialect})`, () => {
      const digest = parsed("SELECT t.region, COUNT(DISTINCT t.customer_id) AS n, (SELECT MAX(amount) FROM payments) AS top FROM (SELECT o.region, o.customer_id FROM orders o WHERE o.status = 'delivered') t GROUP BY t.region", dialect);
      expect(digest.blocks.map((block) => block.kind).sort()).toEqual(["outer", "subquery", "subquery"]);
      expect(digest.blocks[0]!.aggregates).toContainEqual({ fn: "count", distinct: true, columns: [{ table: "t", column: "customer_id" }], windowed: false });
      expect(aggregatingBlocks(digest)).toHaveLength(2);
    });
  }

  it("resolves positional GROUP BY and MySQL's LIMIT offset, count", () => {
    expect(parsed("SELECT region, SUM(x) FROM t GROUP BY 1").blocks[0]!.groupBy).toEqual([{ column: "region" }]);
    expect(parsed("SELECT a FROM t ORDER BY a LIMIT 5, 10", "mysql").blocks[0]!.limit).toBe(10);
  });

  it("finds a LEFT JOIN degenerated by a WHERE predicate, and not a NULL-tolerant one", () => {
    expect(degeneratedOuterJoins(parsed("SELECT c.id FROM customers c LEFT JOIN orders o ON o.cid = c.id WHERE o.amount > 3"))).toEqual([{ block: 0, table: "orders", alias: "o", column: "amount" }]);
    expect(degeneratedOuterJoins(parsed("SELECT c.id FROM customers c LEFT JOIN orders o ON o.cid = c.id WHERE o.id IS NULL"))).toEqual([]);
    expect(degeneratedOuterJoins(parsed("SELECT c.id FROM customers c LEFT JOIN orders o ON o.cid = c.id WHERE COALESCE(o.amount, 0) > 3"))).toEqual([]);
    expect(degeneratedOuterJoins(parsed("SELECT c.id FROM customers c LEFT JOIN orders o ON o.cid = c.id WHERE o.amount > 3 OR o.id IS NULL"))).toEqual([]);
  });

  it("returns unsupported for syntax it cannot read, never throwing", () => {
    expect(digestSql("SELECT * FROM t PIVOT (SUM(x) FOR y IN (1, 2))")).toMatchObject({ status: "unsupported", reason: expect.any(String) });
    expect(digestSql("SELECT 1; SELECT 2")).toMatchObject({ status: "unsupported" });
    expect(digestSql("DELETE FROM t")).toMatchObject({ status: "unsupported", reason: "the statement is not a SELECT" });
  });

  it("extracts multi-dialect current system time references without flagging literal dates or columns", () => {
    expect(parsed("SELECT DATE('now'), DATETIME('now', '-7 day'), STRFTIME('%Y', 'now'), CURRENT_DATE, CURRENT_TIMESTAMP FROM orders", "sqlite").currentTimeExpressions).toEqual([
      "CURRENT_DATE",
      "CURRENT_TIMESTAMP",
      "DATE('now')",
      "DATETIME('now')",
      "STRFTIME('now')",
    ]);
    expect(parsed("SELECT NOW(), CURRENT_DATE, LOCALTIMESTAMP, CLOCK_TIMESTAMP() FROM orders", "postgres").currentTimeExpressions).toEqual([
      "CLOCK_TIMESTAMP",
      "CURRENT_DATE",
      "LOCALTIMESTAMP",
      "NOW",
    ]);
    expect(parsed("SELECT NOW(), CURDATE(), SYSDATE() FROM orders", "mysql").currentTimeExpressions).toEqual([
      "CURDATE",
      "NOW",
      "SYSDATE",
    ]);
    expect(parsed("SELECT CURRENT_DATE(), CURRENT_DATETIME() FROM orders", "bigquery").currentTimeExpressions).toEqual([
      "CURRENT_DATE",
      "CURRENT_DATETIME",
    ]);
    expect(parsed("SELECT GETDATE(), SYSDATE() FROM orders", "snowflake").currentTimeExpressions).toEqual([
      "GETDATE",
      "SYSDATE",
    ]);
    expect(parsed("SELECT DATE('2020-01-01'), STRFTIME('%Y', order_date) FROM orders WHERE note = 'now'", "sqlite").currentTimeExpressions).toEqual([]);
  });

  it("keeps the parser and its AST types inside sql-digest.ts", () => {
    const dir = new URL(".", import.meta.url);
    const users = readdirSync(dir).filter((file) => file.endsWith(".ts") && !file.endsWith(".test.ts") && readFileSync(new URL(file, dir), "utf8").includes("node-sql-parser"));
    expect(users).toEqual(["sql-digest.ts"]);
    const source = readFileSync(new URL("sql-digest.ts", dir), "utf8");
    // A value import for the bundle, but no type import and no re-export of the parser's AST.
    expect(source).not.toMatch(/import type [^\n]*node-sql-parser/);
    expect(source).not.toMatch(/export [^\n]*node-sql-parser/);
  });
});

describe("T5.2 Spec Realization on the digest", () => {
  const conflicts = (fields: SpecFields, sql: string) => evaluateSpecRealization(fields, sql).findings.map((item) => ({ blocking: item.blocking, paths: item.paths, message: item.message }));

  it("flags an inner layer grouped at an outer layer's grain", () => {
    const formula = { "measure.formula": { op: "avg", per: "country", of: { op: "sum", per: "player", of: "runs" } } };
    const misaligned = "WITH x AS (SELECT country, SUM(runs) AS r FROM batting GROUP BY country) SELECT country, AVG(r) FROM x GROUP BY country";
    expect(conflicts(fieldsOf(formula), misaligned)).toEqual([{ blocking: false, paths: ["measure.formula"], message: expect.stringContaining("the grain of the avg per country layer") }]);
    const aligned = "WITH x AS (SELECT country, player_id, SUM(runs) AS r FROM batting GROUP BY country, player_id) SELECT country, AVG(r) FROM x GROUP BY country";
    expect(conflicts(fieldsOf(formula), aligned)).toEqual([]);
  });

  it("flags a count grain the COUNT does not implement", () => {
    const base = { "measure.formula": { op: "count", of: "customers" } };
    const entity = fieldsOf({ ...base, "measure.countGrain": { grain: "entity", keyColumns: ["customer_id"] } });
    expect(conflicts(entity, "SELECT COUNT(*) FROM orders")).toEqual([{ blocking: false, paths: ["measure.countGrain"], message: expect.stringContaining("Count DISTINCT customer_id") }]);
    expect(conflicts(entity, "SELECT COUNT(DISTINCT customer_id) FROM orders")).toEqual([]);
    expect(conflicts(entity, "SELECT COUNT(*) FROM (SELECT customer_id FROM orders GROUP BY customer_id) x")).toEqual([]);
    const rows = fieldsOf({ ...base, "measure.countGrain": { grain: "row" } });
    expect(conflicts(rows, "SELECT COUNT(DISTINCT customer_id) FROM orders")).toEqual([{ blocking: false, paths: ["measure.countGrain"], message: expect.stringContaining("merges equal values") }]);
  });

  it("flags a condition filtered at another stage than declared", () => {
    const fields = fieldsOf({ "population.conditions": [{ condition: "order_count > 5", stage: "HAVING on groups" }] });
    expect(conflicts(fields, "SELECT customer_id, COUNT(*) AS order_count FROM orders WHERE order_count > 5 GROUP BY customer_id")).toEqual([{ blocking: false, paths: ["population.conditions"], message: expect.stringContaining("WHERE/ON on source rows") }]);
    expect(conflicts(fields, "SELECT customer_id, COUNT(*) AS order_count FROM orders GROUP BY customer_id HAVING COUNT(*) > 5 AND order_count > 5")).toEqual([]);
  });

  it("reports unknown coverage, never clear, when the parser cannot read the SQL a digest rule needs", () => {
    const fields = fieldsOf({ "measure.formula": { op: "count", of: "customers" }, "measure.countGrain": { grain: "entity", keyColumns: ["customer_id"] } });
    const report = evaluateSpecRealization(fields, "SELECT COUNT(*) FROM t PIVOT (SUM(x) FOR y IN (1, 2))");
    expect(report.verdicts).toContainEqual(expect.objectContaining({ path: "measure.countGrain", outcome: "not_determinable", reason: expect.stringContaining("the SQL parser could not read the statement") }));
    expect(report.coverage).toMatchObject({ checkId: "spec_realization", ruleVersion: "spec-realization-v2", outcome: "unknown" });
  });
});
